// Write the fixed files for every launch-set template and register them once.
// Per template: src/videos/<id>/{score.ts, schema.ts, meta.ts}. Opus writes score.json and the HTML.
// Registration: the generated module src/videos/launch/index.ts (metas, schemas, sources),
// which meta.ts, schemas.ts, registry.ts, and hyperframesSources.ts spread in.
// Usage: node scripts/launch/scaffold.mjs
import fs from 'node:fs';
import path from 'node:path';
import {LAUNCH} from './briefs.mjs';

const root = path.resolve(import.meta.dirname, '../..');
const write = (p, text) => { fs.mkdirSync(path.dirname(path.join(root, p)), {recursive: true}); fs.writeFileSync(path.join(root, p), text); };
const pascal = (id) => id[0].toUpperCase() + id.slice(1);

for (const b of LAUNCH) {
  const {id} = b;
  const N = pascal(id);
  write(`src/videos/${id}/score.ts`, `import type {BeatScore} from '../beat/score.ts';\nimport json from './score.json' with {type: 'json'};\n\nexport const ${id}Score = json as unknown as BeatScore;\n`);
  write(`src/videos/${id}/schema.ts`, `import type {z} from 'zod';\nimport {librarySchema} from '../../music/schema.ts';\nimport {${id}Score} from './score.ts';\n\n// Sound comes from the music library: audio is {enabled, track}.\nexport const ${id}Schema = librarySchema(${id}Score, ${JSON.stringify(b.roles).replaceAll('"', "'")} as const);\nexport type ${N}Props = z.infer<typeof ${id}Schema>;\n`);
  // Poster frame and motion labels come from the generated design (output/launch/<id>/meta.json) when it exists.
  const gen = path.join(root, 'output/launch', id, 'meta.json');
  const design = fs.existsSync(gen) ? JSON.parse(fs.readFileSync(gen, 'utf8')) : {};
  const motion = (design.motion?.length ? design.motion : ['Kinetic type', 'Mask reveal']).slice(0, 4);
  if (!fs.existsSync(path.join(root, `src/videos/${id}/score.json`))) write(`src/videos/${id}/score.json`, `${JSON.stringify(placeholder(b), null, 2)}\n`);
  if (!fs.existsSync(path.join(root, `src/hyperframes/${id}/index.html`))) write(`src/hyperframes/${id}/index.html`, placeholderHtml(b));
  write(`src/videos/${id}/meta.ts`, `import {beatMeta} from '../beat/schema.ts';\nimport {${id}Score} from './score.ts';\n\nexport const ${id}Meta = beatMeta({\n  id: '${id}', name: '${b.name}', width: ${b.size[0]}, height: ${b.size[1]}, posterFrame: ${Number.isInteger(design.poster) ? design.poster : 0},\n  motion: ${JSON.stringify(motion).replaceAll('"', "'")},\n}, ${id}Score);\n`);
}

// A minimal valid score and composition, so the tree type-checks before Opus has written the real ones.
function placeholder(b) {
  return {beatFrames: 15, scenes: [{type: 'title-reveal', bars: 2, focusBeat: 4, roles: b.roles.filter((r) => r !== 'list'), energy: 3}],
    cues: [{id: 'land', beat: 6, sound: 'impact'}], risers: [],
    ...(b.list ? {list: {role: 'list', label: b.list.label, scene: 0, min: 1, max: b.list.max, itemMax: b.list.itemMax,
      schedules: Object.fromEntries(Array.from({length: b.list.max}, (_, k) => [String(k + 1), Array.from({length: k + 1}, (_, i) => i * 0.5)])),
      accentOffset: 0, voice: 'pluck'}} : {})};
}
function placeholderHtml(b) {
  const [w, h] = b.size;
  return `<!doctype html>\n<html lang="en" data-composition-variables='[]'>\n<head><meta charset="UTF-8" /><meta name="viewport" content="width=${w}, height=${h}" /><script src="__ASSET_BASE__/gsap.min.js"></script><style>__BASE_CSS__ :root { --w: ${w}px; --h: ${h}px; }</style></head>\n<body><div id="root" data-composition-id="main" data-start="0" data-duration="4" data-width="${w}" data-height="${h}"></div><script>__BASE_JS__</script><script>__BEAT_JS__</script>\n<script>const tl = gsap.timeline({paused: true}); CliphouseBeat.mount(tl, __SCORE__, () => {}); window.__timelines = window.__timelines || {}; window.__timelines.main = tl;</script></body></html>\n`;
}

const ids = LAUNCH.map((b) => b.id);
write('src/videos/launch/index.ts', `// Generated by scripts/launch/scaffold.mjs. The launch set's metadata, schemas, and HyperFrames sources.
import type {TemplateMeta} from '../vocab.ts';
import type {VideoSchema} from '../contract.ts';
${ids.map((id) => `import {${id}Meta} from '../${id}/meta.ts';`).join('\n')}
${ids.map((id) => `import {${id}Schema} from '../${id}/schema.ts';`).join('\n')}

export const launchMeta: Record<string, TemplateMeta> = {${ids.map((id) => `${id}: ${id}Meta`).join(', ')}};
export const launchSchemas = {${ids.map((id) => `${id}: ${id}Schema`).join(', ')}} as unknown as Record<string, VideoSchema>;
`);
write('src/videos/launch/sources.ts', `// Generated by scripts/launch/scaffold.mjs. Raw HyperFrames sources, for the Vite bundle only.
${ids.map((id) => `import ${id} from '../../hyperframes/${id}/index.html?raw';`).join('\n')}

export const launchSources: Record<string, string> = {${ids.join(', ')}};
`);
console.log(`Scaffolded ${ids.length} templates.`);
