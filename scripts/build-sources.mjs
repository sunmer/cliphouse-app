const wavCache = new Map();
function presetWav(id, props) {
  if (!wavCache.has(id)) wavCache.set(id, execFileSync(process.execPath, ['--input-type=module', '-e', isBeat(id)
    ? `import {songWav} from './src/videos/song/index.ts'; import song from './src/videos/${id}/song.ts'; import fs from 'node:fs';
     const score = JSON.parse(fs.readFileSync('src/videos/${id}/score.json', 'utf8'));
     process.stdout.write(Buffer.from(songWav(score, song, ${JSON.stringify(props)})));`
    : `import {musicWav} from './src/videos/music/index.ts'; import fs from 'node:fs';
     const score = JSON.parse(fs.readFileSync('src/videos/${id}/score.json', 'utf8'));
     process.stdout.write(Buffer.from(musicWav(score, ${JSON.stringify(props)})));`], {cwd: root, maxBuffer: 64 * 1024 * 1024}));
  return wavCache.get(id);
}
