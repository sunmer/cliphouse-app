const {chromium, devices} = require('playwright');
(async () => {
  const b = await chromium.launch({args: ['--autoplay-policy=no-user-gesture-required']});
  const p = await (await b.newContext(devices['iPhone 14'])).newPage();
  const errors = [];
  p.on('pageerror', (e) => errors.push(e.message));
  await p.goto('http://localhost:5190/#/v/poc-ticker-beat');
  await p.waitForTimeout(2500);
  await p.click('button[aria-label="Play sound"]');
  await p.waitForTimeout(2500);
  console.log('audio', JSON.stringify(await p.evaluate(() => window.__cliphouseAudio?.())));
  await p.click('button[aria-label="Pause"]');
  const box = await (await p.$('[class*=timeline]')).boundingBox();
  await p.mouse.click(box.x + box.width * 0.6, box.y + box.height / 2);
  await p.waitForTimeout(1000);
  await p.screenshot({path: 'output/poc/shots/beat-mobile.png'});
  await p.click('.text-hit[aria-label="Edit Point 3"]');
  await p.fill('.inline-editor textarea', 'Ends Sunday');
  console.log('editing count', 1);
  await p.click('button[aria-label="Save list"]');
  await p.waitForTimeout(400);
  console.log('ready right after edit', await p.$eval('.sound-btn', (e) => e.dataset.audioReady));
  await p.waitForTimeout(2500);
  console.log('ready later', await p.$eval('.sound-btn', (e) => e.dataset.audioReady));
  await p.screenshot({path: 'output/poc/shots/beat-mobile-one.png'});
  await p.click('button[aria-label="Play"]');
  await p.waitForTimeout(3000);
  console.log('audio after', JSON.stringify(await p.evaluate(() => window.__cliphouseAudio?.())));
  console.log('errors', errors);
  await b.close();
})();
