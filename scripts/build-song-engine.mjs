// Build the song engine from the vendored synth-music-from-code skill: dsp.js, instruments.js, and mix.js,
// joined into one ES module at 48 kHz (the export sample rate). The engine is plain sample-by-sample JavaScript,
// so Node and the browser produce identical samples.
// Usage: node scripts/build-song-engine.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const src = path.join(root, 'vendor/synth-music-from-code/scripts/engine');
const out = path.join(root, 'src/videos/song/engine.js');
const body = ['dsp.js', 'instruments.js', 'mix.js'].map((f) => {
  let code = fs.readFileSync(path.join(src, f), 'utf8').replace(/^'use strict';\n/m, '');
  if (f === 'dsp.js') {
    if (!/^var SR = 44100;$/m.test(code)) throw new Error('dsp.js no longer sets SR = 44100; update this script.');
    code = code.replace(/^var SR = 44100;$/m, 'var SR = 48000;');
  }
  return `// ---- ${f} ----\n${code}`;
}).join('\n');
const code = `// Generated by scripts/build-song-engine.mjs from vendor/synth-music-from-code/scripts/engine. Do not edit.
${body}
export {renderSong, encodeWav, stepDur, nm, SR, lufs, truePeakDb, biquadRun, V};
`;
if (process.argv.includes('--check')) {
  if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== code) throw new Error('src/videos/song/engine.js is out of date. Run node scripts/build-song-engine.mjs.');
  console.log('Song engine is current.');
} else {
  fs.mkdirSync(path.dirname(out), {recursive: true});
  fs.writeFileSync(out, code);
  console.log('Wrote', path.relative(root, out), code.length, 'bytes');
}
