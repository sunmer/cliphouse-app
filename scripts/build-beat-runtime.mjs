// Bundle the HyperFrames beat runtime (plan + list rows + timeline mount) into one IIFE that templates inline.
// Usage: node scripts/build-beat-runtime.mjs [--check]
import {build} from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const out = path.join(root, 'src/hyperframes/shared/beat.js');
const result = await build({
  entryPoints: [path.join(root, 'src/hyperframes/shared/beat-entry.ts')],
  bundle: true, format: 'iife', globalName: 'CliphouseBeat', target: 'es2020', write: false, legalComments: 'none',
  banner: {js: '// Generated by scripts/build-beat-runtime.mjs from src/hyperframes/shared/beat-entry.ts. Do not edit.'},
});
const code = result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== code) throw new Error('src/hyperframes/shared/beat.js is out of date. Run npm run beat:runtime.');
  console.log('Beat runtime is current.');
} else {
  fs.writeFileSync(out, code);
  console.log('Wrote', path.relative(root, out), code.length, 'bytes');
}
